import 'dart:async';
import 'package:flutter/foundation.dart';
import 'package:flutter_webrtc/flutter_webrtc.dart';
import 'package:permission_handler/permission_handler.dart';

class WebRTCService {
  RTCPeerConnection? _peerConnection;
  MediaStream? _localStream;
  MediaStream? _remoteStream;
  final List<RTCIceCandidate> _queuedCandidates = [];

  Function(MediaStream stream)? onLocalStreamReady;
  Function(MediaStream stream)? onRemoteStreamReady;
  Function(RTCIceCandidate candidate)? onIceCandidateGenerated;

  MediaStream? get localStream => _localStream;
  MediaStream? get remoteStream => _remoteStream;
  bool get hasActiveConnection => _peerConnection != null;

  static const Map<String, dynamic> _iceServers = {
    'iceServers': [
      {'urls': 'stun:stun.l.google.com:19302'},
      {'urls': 'stun:stun1.l.google.com:19302'},
      {'urls': 'stun:stun2.l.google.com:19302'},
      {'urls': 'stun:stun3.l.google.com:19302'},
    ],
    'sdpSemantics': 'unified-plan',
  };

  /// Requests runtime audio/video permissions from the operating system.
  Future<bool> requestPermissions({bool isVideo = false}) async {
    try {
      final micStatus = await Permission.microphone.request();
      if (!micStatus.isGranted) {
        debugPrint('[WebRTC] Microphone permission was not granted: $micStatus');
        return false;
      }

      if (isVideo) {
        final camStatus = await Permission.camera.request();
        if (!camStatus.isGranted) {
          debugPrint('[WebRTC] Camera permission was not granted: $camStatus');
          return false;
        }
      }

      return true;
    } catch (e) {
      debugPrint('[WebRTC] Permission request fallback warning: $e');
      return true;
    }
  }

  /// Captures local microphone (and camera if video) using device hardware.
  Future<MediaStream?> initLocalStream({bool isVideo = false}) async {
    try {
      await requestPermissions(isVideo: isVideo);

      final mediaConstraints = <String, dynamic>{
        'audio': {
          'echoCancellation': true,
          'noiseSuppression': true,
          'autoGainControl': true,
        },
        'video': isVideo
            ? {
                'mandatory': {
                  'minWidth': '640',
                  'minHeight': '480',
                  'minFrameRate': '30',
                },
                'facingMode': 'user',
                'optional': [],
              }
            : false,
      };

      _localStream = await navigator.mediaDevices.getUserMedia(mediaConstraints);
      onLocalStreamReady?.call(_localStream!);
      return _localStream;
    } catch (e) {
      debugPrint('[WebRTC] Failed to capture local media stream: $e');
      return null;
    }
  }

  /// Initializes RTCPeerConnection and attaches local audio/video tracks.
  Future<RTCPeerConnection?> createPeerConnectionInstance({bool isVideo = false}) async {
    try {
      if (_localStream == null) {
        await initLocalStream(isVideo: isVideo);
      }

      _peerConnection = await createPeerConnection(_iceServers);

      // Add local audio and video tracks to the peer connection
      if (_localStream != null) {
        for (final track in _localStream!.getTracks()) {
          await _peerConnection!.addTrack(track, _localStream!);
        }
      }

      // Listen for incoming remote tracks (remote voice/video stream)
      _peerConnection!.onTrack = (RTCTrackEvent event) {
        debugPrint('[WebRTC] Remote track received: ${event.track.kind}');
        if (event.streams.isNotEmpty) {
          _remoteStream = event.streams[0];
          onRemoteStreamReady?.call(_remoteStream!);
        }
      };

      // Listen for local ICE candidates generated by STUN
      _peerConnection!.onIceCandidate = (RTCIceCandidate candidate) {
        if (candidate.candidate != null && candidate.candidate!.isNotEmpty) {
          onIceCandidateGenerated?.call(candidate);
        }
      };

      _peerConnection!.onConnectionState = (RTCPeerConnectionState state) {
        debugPrint('[WebRTC] Connection state changed: $state');
      };

      return _peerConnection;
    } catch (e) {
      debugPrint('[WebRTC] Error initializing peer connection: $e');
      return null;
    }
  }

  /// Caller creates SDP offer to send to the remote participant.
  Future<RTCSessionDescription?> createOffer({bool isVideo = false}) async {
    try {
      if (_peerConnection == null) {
        await createPeerConnectionInstance(isVideo: isVideo);
      }

      final constraints = <String, dynamic>{
        'offerToReceiveAudio': 1,
        'offerToReceiveVideo': isVideo ? 1 : 0,
      };

      final offer = await _peerConnection!.createOffer(constraints);
      await _peerConnection!.setLocalDescription(offer);
      debugPrint('[WebRTC] Created local SDP offer');
      return offer;
    } catch (e) {
      debugPrint('[WebRTC] Error creating offer: $e');
      return null;
    }
  }

  /// Callee handles incoming SDP offer, sets remote description, and generates SDP answer.
  Future<RTCSessionDescription?> handleOffer(String sdp, {bool isVideo = false}) async {
    try {
      if (_peerConnection == null) {
        await createPeerConnectionInstance(isVideo: isVideo);
      }

      final remoteDesc = RTCSessionDescription(sdp, 'offer');
      await _peerConnection!.setRemoteDescription(remoteDesc);
      debugPrint('[WebRTC] Set remote SDP offer');

      // Flush any queued ICE candidates that arrived before the offer
      for (final candidate in _queuedCandidates) {
        await _peerConnection!.addCandidate(candidate);
      }
      _queuedCandidates.clear();

      final constraints = <String, dynamic>{
        'offerToReceiveAudio': 1,
        'offerToReceiveVideo': isVideo ? 1 : 0,
      };

      final answer = await _peerConnection!.createAnswer(constraints);
      await _peerConnection!.setLocalDescription(answer);
      debugPrint('[WebRTC] Created and set local SDP answer');
      return answer;
    } catch (e) {
      debugPrint('[WebRTC] Error handling offer: $e');
      return null;
    }
  }

  /// Caller handles SDP answer sent back by the callee.
  Future<void> handleAnswer(String sdp) async {
    try {
      if (_peerConnection == null) return;
      final remoteDesc = RTCSessionDescription(sdp, 'answer');
      await _peerConnection!.setRemoteDescription(remoteDesc);
      debugPrint('[WebRTC] Set remote SDP answer successfully');

      // Flush queued candidates
      for (final candidate in _queuedCandidates) {
        await _peerConnection!.addCandidate(candidate);
      }
      _queuedCandidates.clear();
    } catch (e) {
      debugPrint('[WebRTC] Error handling answer: $e');
    }
  }

  /// Adds remote ICE candidate.
  Future<void> handleCandidate(Map<String, dynamic> candidateMap) async {
    try {
      final cand = RTCIceCandidate(
        candidateMap['candidate'] as String?,
        candidateMap['sdpMid'] as String?,
        candidateMap['sdpMLineIndex'] as int?,
      );

      if (_peerConnection != null) {
        final remoteDesc = await _peerConnection!.getRemoteDescription();
        if (remoteDesc != null) {
          await _peerConnection!.addCandidate(cand);
          debugPrint('[WebRTC] Added remote ICE candidate');
          return;
        }
      }

      // If remote description is not set yet, queue the candidate
      _queuedCandidates.add(cand);
    } catch (e) {
      debugPrint('[WebRTC] Error adding candidate: $e');
    }
  }

  /// Mutes or unmutes local microphone.
  void setMicrophoneMute(bool isMuted) {
    if (_localStream != null) {
      for (final track in _localStream!.getAudioTracks()) {
        track.enabled = !isMuted;
      }
      debugPrint('[WebRTC] Microphone muted: $isMuted');
    }
  }

  /// Enables or disables local camera feed.
  void setVideoEnabled(bool isEnabled) {
    if (_localStream != null) {
      for (final track in _localStream!.getVideoTracks()) {
        track.enabled = isEnabled;
      }
      debugPrint('[WebRTC] Camera video enabled: $isEnabled');
    }
  }

  /// Toggles between device speaker and earpiece.
  void setSpeakerphoneOn(bool isSpeakerOn) {
    try {
      if (_localStream != null) {
        for (final track in _localStream!.getAudioTracks()) {
          track.enableSpeakerphone(isSpeakerOn);
        }
      }
      debugPrint('[WebRTC] Speakerphone set to: $isSpeakerOn');
    } catch (e) {
      debugPrint('[WebRTC] Failed to toggle speakerphone: $e');
    }
  }

  /// Flips front/rear camera.
  Future<void> switchCamera() async {
    try {
      final videoTracks = _localStream?.getVideoTracks();
      if (videoTracks != null && videoTracks.isNotEmpty) {
        await Helper.switchCamera(videoTracks.first);
        debugPrint('[WebRTC] Camera switched');
      }
    } catch (e) {
      debugPrint('[WebRTC] Error switching camera: $e');
    }
  }

  /// Ends WebRTC session and releases media hardware.
  Future<void> dispose() async {
    try {
      _localStream?.getTracks().forEach((track) {
        track.stop();
      });
      await _localStream?.dispose();
      _localStream = null;

      _remoteStream?.getTracks().forEach((track) {
        track.stop();
      });
      await _remoteStream?.dispose();
      _remoteStream = null;

      await _peerConnection?.close();
      await _peerConnection?.dispose();
      _peerConnection = null;

      _queuedCandidates.clear();
      debugPrint('[WebRTC] Disposed peer connection and released media devices');
    } catch (e) {
      debugPrint('[WebRTC] Error disposing WebRTC resources: $e');
    }
  }
}

